"""Validate the shared UI catalog and build its offline, ES5 browser copy."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
catalog=json.loads((root/'locales/interface.json').read_text())
for key,values in catalog.items():
 assert {'en','es','de'}<=set(values)<= {'fr','en','es','de'},key
 for language,text in values.items():
  assert text and set(re.findall(r'\{\w+\}',values.get('fr',key)))==set(re.findall(r'\{\w+\}',text)),(key,language)
bootstrap=(root/'tools/locale-bootstrap.js').read_text()
(root/'PWA/i18n-catalog.js').write_text('// Generated by tools/build-locales.py; edit locales/interface.json.\nwindow.S2ATranslations='+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n'+bootstrap)
for language,description in [('fr','Préparez et pilotez des spectacles multimédias autonomes.'),('en','Prepare and run self-contained multimedia shows.'),('es','Prepara y dirige espectáculos multimedia autónomos.'),('de','Eigenständige Multimedia-Shows vorbereiten und steuern.')]:
 manifest=json.loads((root/'PWA/manifest.webmanifest').read_text());manifest.update(lang=language,description=description)
 name='manifest.webmanifest' if language=='fr' else f'manifest.{language}.webmanifest'
 (root/'PWA'/name).write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(f'Validated {len(catalog)} UI keys in FR/EN/ES/DE; generated offline catalog and manifests.')
